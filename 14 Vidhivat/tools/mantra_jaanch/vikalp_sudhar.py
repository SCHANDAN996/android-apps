def saaf(s):
    return re.sub(r'[ \t]+\n', '\n', s).strip()


def main():
    gin = {i: 0 for i in range(len(BADLAV))}
    for path in sorted(glob.glob(os.path.join(VIDHI, '**', '*.json'), recursive=True)):
        if os.path.basename(path).startswith('_'):
            continue
        raw = io.open(path, encoding='utf-8', newline='').read()
        nl = '\r\n' if '\r\n' in raw else '\n'
        indent = len(re.search(r'\n( +)"', raw).group(1))
        v = json.loads(raw)
        chhua = False
        for c in v.get('charan', []):
            m = c.get('mantra')
            if not m or not m.get('vikalp'):
                continue
            purana = m['vikalp']
            naya = purana
            for i, (a, b) in enumerate(BADLAV):
                if a in naya:
                    naya = naya.replace(a, b)
                    gin[i] += 1
            naya = saaf(naya)
            if naya != purana:
                m['vikalp'] = naya
                chhua = True
        if chhua:
            out = json.dumps(v, ensure_ascii=False, indent=indent).replace('\n', nl)
            if raw.endswith(('\n', '\r\n')):
                out += nl
            io.open(path, 'w', encoding='utf-8', newline='').write(out)
    # generator में लिखे `vikalp` भी
    s = io.open(GEN, encoding='utf-8', newline='').read()
    g = s
    for i, (a, b) in enumerate(BADLAV):
        a_py = a.replace('"', '\\"')
        b_py = b.replace('"', '\\"')
        if a_py in g:
            g = g.replace(a_py, b_py)
            gin[i] += 1
    if g != s:
        io.open(GEN, 'w', encoding='utf-8', newline='').write(g)
    for i, n in gin.items():
        print('%2d' % i, n, '|', BADLAV[i][0][:50].replace('\n', ' '))


if __name__ == '__main__':
    main()
