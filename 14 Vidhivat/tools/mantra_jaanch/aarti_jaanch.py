def lagao(naam, e, v):
    kh = v['khand']
    for k in kh:
        k['_dev'] = k['dev']
    for i, jode in e.get('sudhar', {}).items():
        k = kh[i - 1]
        dev = k['dev']
        for a, b in jode:
            assert dev.count(a) == 1, (naam, i, a)
            dev = dev.replace(a, b)
        k['dev'] = dev
    for i, (dev, arth) in e.get('badlo', {}).items():
        kh[i - 1]['dev'] = dev
        if arth is not None:
            kh[i - 1]['arth'] = arth
    for i, arth in e.get('arth', {}).items():
        kh[i - 1]['arth'] = arth
    nayi = []
    for i, k in enumerate(kh, 1):
        if i not in set(e.get('hatao', [])):
            nayi.append(k)
        if i in e.get('jodo', {}):
            dev, arth = e['jodo'][i]
            nayi.append(dict(shirshak='पद', dev=dev, roman='', arth=arth, audio='', sthiti=k.get('sthiti', 'draft')))
    # रोमन पाठ से ही; «पद N» फिर से गिनो
    n = 0
    for k in nayi:
        if k.pop('_dev', None) != k['dev']:   # बदले पाठ का ही रोमन नया
            k['roman'] = roman_hindi(k['dev'])
        if not k.get('dohraav'):
            n += 1
            if k['shirshak'].startswith('पद'):
                k['shirshak'] = 'पद ' + dev_ank(n)
    v['khand'] = nayi
    v['strot']['paddhati'] = PADDHATI
    v['strot']['note'] = e['note']
    v['bharosa'] = e.get('bharosa', 'uncha')
    return v


def mool(p):
    """फ़ैसले हमेशा इस काम से पहले वाले पाठ पर लगें — दोबारा चलाने पर पद दोबारा न हटें/जुड़ें।"""
    rel = os.path.relpath(p, os.path.join(JAD, '..', '..')).replace(os.sep, '/')
    r = subprocess.run(['git', 'show', MOOL_COMMIT + ':./' + rel], cwd=os.path.join(JAD, '..', '..'),
                       capture_output=True)
    if r.returncode == 0:
        return r.stdout.decode('utf-8')
    return io.open(p, encoding='utf-8', newline='').read()


def main(likho):
    for naam, e in AARTI.items():
        p = os.path.join(PAATH, naam + '.json')
        raw = mool(p)
        nl = '\r\n' if '\r\n' in raw else '\n'
        purana = json.loads(raw)
        v = lagao(naam, e, json.loads(raw))
        assert len(v['strot']['note']) <= 600, (naam, len(v['strot']['note']))
        print('##', naam, 'पद:', len(purana['khand']), '→', len(v['khand']), '| भरोसा', purana['bharosa'], '→',
              v['bharosa'], '| ⓘ', len(v['strot']['note']))
        pd = {k['dev'] for k in purana['khand']}
        nd = {k['dev'] for k in v['khand']}
        for d in [k['dev'] for k in purana['khand'] if k['dev'] not in nd]:
            print('  -', d.replace('\n', ' / '))
        for d in [k['dev'] for k in v['khand'] if k['dev'] not in pd]:
            print('  +', d.replace('\n', ' / '))
        if likho:
            out = json.dumps(v, ensure_ascii=False, indent=2).replace('\n', nl)
            if raw.endswith(('\n', '\r\n')):
                out += nl
            likho_file(p, out)


def likho_file(p, out):
    """Windows पर कभी-कभी फ़ाइल पल भर को रुकी मिलती है (OSError 22) — थोड़ा रुककर फिर।"""
    for koshish in range(20):
        try:
            with io.open(p, 'w', encoding='utf-8', newline='') as f:
                f.write(out)
            return
        except OSError:
            time.sleep(0.5)
    raise SystemExit('लिख नहीं पाए: ' + p)


