    #    अकेली चलने वाली पूजा में बुलावा भी चाहिए और विदा भी; विदा
    #    (क्षमा) पहले से है, बुलावा नहीं था।
    #
    #    ⚠️ आवाहन का मंत्र **कलश स्थापना से उठाया जा रहा है**, यहाँ लिखा
    #    नहीं — वही नियम जो `devi_kshama()` पर लगता है, ताकि दोनों जगह
    #    एक ही पाठ और एक ही स्रोत रहे (→ D-072)।
