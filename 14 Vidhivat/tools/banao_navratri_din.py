def _bhara_mantra_bachao(path: Path, naya: dict) -> None:
    """पहरा (→ D-138, J-004): जो मंत्र फ़ाइल में भरा है, उसे ख़ाली से कभी न बदलो।

    किसी कदम में फ़ाइल का मंत्र भरा हो और नया ख़ाली — तो रुक जाओ; पहले भरा पाठ
    (स्रोत सहित) इस generator में लाओ। हाथ से भरे पाठ चुपचाप नहीं मिटेंगे।
    """
    if not path.exists():
        return
    purana = json.loads(path.read_text(encoding="utf-8"))
    naye = {c["shirshak"]: c for c in naya.get("charan", [])}
    for c in purana.get("charan", []):
        pm = (c.get("mantra") or {}).get("devanagari", "").strip()
        nm = ((naye.get(c["shirshak"]) or {}).get("mantra") or {}).get("devanagari", "").strip()
        if pm and not nm:
            raise SystemExit(
                f"{path.name}: «{c['shirshak']}» का भरा मंत्र ख़ाली हो जाता — "
                "पहले वह पाठ generator में लाइए (→ D-138)")


def main() -> None:
    base = json.loads((VIDHI / "nitya_pooja.json").read_text(encoding="utf-8"))
    NIRGAM.mkdir(parents=True, exist_ok=True)
    for ank, (devi, roman_devi, bhog) in DEVI.items():
        data = vidhi(base, ank, devi, roman_devi, bhog)
        _bhara_mantra_bachao(NIRGAM / f"navratri_din_{ank}.json", data)
        (NIRGAM / f"navratri_din_{ank}.json").write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    for naam, data in {
        "navratri_sankshipt": sankshipt(base),
        "navratri_navami_havan": navami(base),
        "vijayadashami": dashami(base),
    }.items():
        _bhara_mantra_bachao(NIRGAM / f"{naam}.json", data)
        (NIRGAM / f"{naam}.json").write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )

    # अष्टमी `navratri/` में नहीं जाती — वह पूजाओं की सूची में अपने नाम से
    # भी खुलती है, और `VidhiBhandar.pathFor` सिर्फ़ `navratri_*` तथा
    # `vijayadashami` को उस फ़ोल्डर में ढूँढता है।
    ashtami_data = ashtami(base)
    _bhara_mantra_bachao(VIDHI / "durga_ashtami_kanya_poojan.json", ashtami_data)
    (VIDHI / "durga_ashtami_kanya_poojan.json").write_text(
        json.dumps(ashtami_data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
