def saajhe(base: dict, *naam: str) -> list[dict]:
    """नित्य पूजा से साझे कदम उठाओ — एक ही जगह से, हर फ़ाइल के लिए।

    गणेश वाले कदम पर नित्य पूजा में लिखा है कि तुलसी आगे विष्णु-पूजन में
    चढ़ेगी। नवरात्रि की सामग्री में तुलसी है ही नहीं, इसलिए वह वाक्य
    यहाँ झूठा हो जाता — हटा दिया जाता है।
    """
    by_name = {c["shirshak"]: c for c in base["charan"]}
    out = []
    for n in naam:
        c = copy.deepcopy(by_name[n])
        if n == "गणेश स्मरण":
            c["vivaran"] = c["vivaran"].split(" गणेश जी को तुलसी न चढ़ाएँ")[0]
        out.append(c)
    return out


