def likho():
    raw = padho()
    ank = []
    for a, b, _, _ in KHAND:
        ank += list(range(a, b + 1))
    assert ank == list(range(1, KUL + 1)), 'खंडों में श्लोक 1…%d पूरे/क्रम से नहीं' % KUL
    blocks = []
    for a, b, naam, arth in KHAND:
        rng = dev_ank(a) if a == b else '%s–%s' % (dev_ank(a), dev_ank(b))
        lines = ['# %s · श्लोक %s' % (naam, rng)]
        for num, text, vakta in raw:
            if not (a <= num <= b):
                continue
            if vakta:
                lines.append(vakta + ' ।')
            lines.append(text)
        assert not re.search('[A-Za-z0-9]', arth), arth
        lines.append('= ' + arth)
        blocks.append('\n'.join(lines))
    out = os.path.join(DST, 'paath', 'gajendra.txt')
    with io.open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(khula('\n\n'.join(blocks)) + '\n')
    print('लिखा', os.path.relpath(out, DST), '·', len(KHAND), 'खंड ·',
          sum(len(b.split('\n')) for b in blocks), 'पंक्तियाँ')
    return len(KHAND)


