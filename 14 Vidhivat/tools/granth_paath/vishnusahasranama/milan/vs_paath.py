def shlok(lines, n, hissa):
    a, b = lines[2 * n - 2], lines[2 * n - 1]
    out = []
    if (hissa, n) in UVACH:
        out.append(UVACH[(hissa, n)])
    return out + [a + ' ।', b + '॥']


def blk(shirshak, mool, arth):
    assert not re.search('[A-Za-z0-9]', arth), (shirshak, arth)
    return '# %s\n%s\n= %s' % (shirshak, '\n'.join(mool), arth)


def main(dst):
    m = json.load(io.open('mool.json', encoding='utf-8'))
    N = naam_padho()
    os.makedirs(os.path.join(dst, 'paath'), exist_ok=True)

    b1 = [blk(*x) for x in MANGAL]
    assert len(PURVA) == 13
    for n in range(1, 14):
        b1.append(blk('श्लोक ' + da(n), shlok(m['purva'], n, 'purva'), PURVA[n - 1]))

    b2, ank = [], 0
    for n in range(1, 108):
        pehla = ank + 1
        ank += len(N[n])
        # नाम के भीतर का "—" सूची में उलझाता है — वहाँ अल्पविराम
        arth = '(नाम %s–%s) %s।' % (da(pehla), da(ank), '; '.join(
            '%s — %s' % (a, b.replace(' — ', ', ').replace('; ', ', ')) for a, b in N[n]))
        b2.append(blk('श्लोक ' + da(n), shlok(m['naam'], n, 'naam'), arth))
    assert ank == 1000

    b3 = []
    assert len(PHAL) == 22
    for n in range(1, 23):
        b3.append(blk('श्लोक ' + da(n), shlok(m['phal'], n, 'phal'), PHAL[n - 1]))
    b3.append(blk('समापन', *SAMAPAN))

    for key, bl in (('01', b1), ('02', b2), ('03', b3)):
        with io.open(os.path.join(dst, 'paath', key + '.txt'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n\n'.join(bl) + '\n')
        print(key, len(bl))


if __name__ == '__main__':
    main(sys.argv[1])
