def kram(bane):
    p = os.path.join(DST, 'kram.json')
    k = json.loads(io.open(p, encoding='utf-8').read())
    k['strot']['sanatsujat'] = {
        'paddhati': 'महाभारत, उद्योग पर्व (सनत्सुजात पर्व) — छपी पुस्तकों के अध्याय ४२–४६, कुल १९२ श्लोक',
        'kshetra': 'सब जगह',
        'note': NOTE,
    }
    for adhyay, key, kul in ADHYAY:
        naam, ek, parichay = PANNE[key]
        k['paath'][key] = {
            'naam': naam,
            'upnaam': ['सनत्सुजातीय', 'सनत्सुजात पर्व', 'सनत्सुजात', 'धृतराष्ट्र और सनत्सुजात', 'उद्योग पर्व'],
            'ekLine': ek,
            'parichay': parichay,
            'shlok': bane[key],
            'gintiNaam': 'खंड',
            'prakar': 'granth',
            'bhasha': 'संस्कृत',
            'bharosa': 'uncha',
            'devta': 'ब्रह्म — परमात्मा',
            'rachnakar': 'महाभारत, उद्योग पर्व — महर्षि वेदव्यास',
            'kabPadhein': 'जब मन हो। यह पूजा का पाठ नहीं है — उपदेश है; धीरे-धीरे, अर्थ के साथ पढ़ने की चीज़।',
            'kaisePadhein': KAISE,
            'strot': 'sanatsujat',
        }
    sab = [key for _, key, _ in ADHYAY]
    k['hisse'] = [h for h in k['hisse'] if not (set(h['paath']) & set(sab))]
