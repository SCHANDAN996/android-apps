ADHYAY = [(42, 'ss1', 46), (43, 'ss2', 63), (44, 'ss3', 31), (45, 'ss4', 21), (46, 'ss5', 31)]


def padho(adhyay, kul):
    """[(श्लोक-अंक, पंक्ति, वक्ता या '')]"""
    raw = []
    vakta = ''
    for line in io.open(os.path.join(VDIR, 'vss_%d.txt' % adhyay), encoding='utf-8'):
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        if s.startswith('@'):
            vakta = s[1:].strip()
            continue
        m = re.search(r'॥([०-९]+)॥$', s)
        num = int(''.join(str(ANK.index(c)) for c in m.group(1))) if m else None
        raw.append([num, re.sub(r'\s*॥[०-९]+॥$', ' ॥', s) if m else s, vakta])
        vakta = ''
    nxt = None
    for r in reversed(raw):
        if r[0] is None:
            r[0] = nxt
        else:
            nxt = r[0]
    apne = [x for x in SUDHAR if x[0] == adhyay]
    lage = set()
    for r in raw:
        for _, n, a, b in apne:
            if r[0] == n and a in r[1]:
                r[1] = r[1].replace(a, b)
                lage.add((n, a))
    assert len(lage) == len(apne), [x for x in apne if (x[1], x[2]) not in lage]
    assert [r[0] for r in raw if r[1].endswith('॥')] == list(range(1, kul + 1)), 'श्लोक-अंक क्रम में नहीं: %d' % adhyay
    # छपाई में पाद के अंत पर टूटा शब्द («…ब्रह्मचर्य-» / «ममृत्यवे…») — दोनों टुकड़े एक पंक्ति में
    out = []
    for r in raw:
        if out and out[-1][1].endswith('-'):
            assert not r[2], r
            out[-1][1] = out[-1][1][:-1] + r[1]
        else:
            out.append(r)
    return out


