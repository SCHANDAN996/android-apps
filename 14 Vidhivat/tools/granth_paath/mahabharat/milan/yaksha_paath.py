def likho():
    raw = padho()
    # ढकाव: 1…133, बिना छेद और बिना दोहराव
    ank = []
    for a, b, _, _ in KHAND:
        ank += list(range(a, b + 1))
    assert ank == list(range(1, 134)), 'खंडों में श्लोक 1…133 पूरे/क्रम से नहीं'
    blocks = []
    prashn = 0
    for a, b, naam, arth in KHAND:
        if naam is None:
            prashn += 1
            naam = 'प्रश्न ' + dev_ank(prashn)
        rng = dev_ank(a) if a == b else '%s–%s' % (dev_ank(a), dev_ank(b))
        lines = ['# %s · श्लोक %s' % (naam, rng)]
        for num, text, vakta in raw:
            if not (a <= num <= b):
                continue
            if vakta:
                lines.append(vakta + ' ।')
            t = text
            if t.endswith('।'):
                t = t[:-1].rstrip() + ' ।'
            lines.append(t)
        assert not re.search('[A-Za-z0-9]', arth), arth
        lines.append('= ' + arth)
        blocks.append('\n'.join(lines))
    out = os.path.join(DST, 'paath', 'yaksha.txt')
    with io.open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(khula('\n\n'.join(blocks)) + '\n')
    print('लिखा', out, '·', len(KHAND), 'खंड ·', prashn, 'प्रश्न-खंड ·', sum(len(b.split('\n')) for b in blocks), 'पंक्तियाँ')
    return len(KHAND)


