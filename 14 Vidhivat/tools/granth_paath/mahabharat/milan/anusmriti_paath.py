SUDHAR = []


def padho():
    """[(श्लोक-अंक, पंक्ति, वक्ता या '')]"""
    raw = []
    vakta = ''
    for f in sorted(glob.glob(os.path.join(VDIR, 'vanu_*.txt'))):
        for line in io.open(f, encoding='utf-8'):
            s = line.strip()
            if not s or s.startswith('#'):
                continue
            if s.startswith('@'):
                vakta = s[1:].strip()
                continue
            m = re.search(r'॥(\d+)॥$', s)
            raw.append([int(m.group(1)) if m else None, re.sub(r'\s*॥\d+॥$', ' ॥', s) if m else s, vakta])
            vakta = ''
    nxt = None
    for r in reversed(raw):
        if r[0] is None:
            r[0] = nxt
        else:
            nxt = r[0]
    lage = set()
    for r in raw:
        for n, a, b in SUDHAR:
            if r[0] == n and a in r[1]:
                r[1] = r[1].replace(a, b)
                lage.add((n, a))
    assert len(lage) == len(SUDHAR), [x for x in SUDHAR if (x[0], x[1]) not in lage]
    assert [r[0] for r in raw if r[1].endswith('॥')] == list(range(1, KUL + 1)), 'श्लोक-अंक क्रम में नहीं'
    return raw


