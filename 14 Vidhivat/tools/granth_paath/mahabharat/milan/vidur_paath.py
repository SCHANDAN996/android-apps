def kram(bane):
    """kram.json: स्रोत `vidur`, आठ पन्ने, और नया हिस्सा सनत्सुजातीय से पहले (अध्याय ३३–४० उसके ४२–४६ से पहले आते हैं)।"""
    p = os.path.join(DST, 'kram.json')
    k = json.loads(io.open(p, encoding='utf-8').read())
    k['strot']['vidur'] = {
        'paddhati': 'महाभारत, उद्योग पर्व (प्रजागर पर्व) — छपी पुस्तकों के अध्याय ३३–४०, कुल ५९३ श्लोक',
        'kshetra': 'सब जगह',
        'note': NOTE,
    }
    for adhyay, key, kul in ADHYAY:
        naam, ek, parichay = PANNE[key]
        k['paath'][key] = {
            'naam': naam,
            'upnaam': ['विदुर नीति', 'विदुरनीति', 'विदुर और धृतराष्ट्र', 'प्रजागर पर्व', 'उद्योग पर्व'],
            'ekLine': ek,
            'parichay': parichay,
            'shlok': bane[key],
            'gintiNaam': 'खंड',
            'prakar': 'granth',
            'bhasha': 'संस्कृत',
            'bharosa': 'uncha',
            'devta': 'धर्म और नीति',
            'rachnakar': 'महाभारत, उद्योग पर्व — महर्षि वेदव्यास',
            'kabPadhein': 'जब मन हो। यह पूजा का पाठ नहीं है — नीति की बातें हैं, जो घर में मिलकर पढ़ने और सुनाने '
                          'लायक़ हैं।',
            'kaisePadhein': KAISE,
            'strot': 'vidur',
        }
    sab = [key for _, key, _ in ADHYAY]
    hisse = [h for h in k['hisse'] if not (set(h['paath']) & set(sab))]
    jagah = next(i for i, h in enumerate(hisse) if 'ss1' in h['paath'])
    hisse.insert(jagah, {'shirshak': 'विदुर नीति — उद्योग पर्व से', 'paath': sab})
    k['hisse'] = hisse
    k['parichay'] = granth_parichay.parichay(k)
    with io.open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(khula(json.dumps(k, ensure_ascii=False, indent=2)) + '\n')
    print('kram.json · ⓘ नोट', len(khula(NOTE)), 'अक्षर · पन्ने', len(sab))


