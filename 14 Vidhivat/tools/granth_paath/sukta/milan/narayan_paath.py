def blk(shirshak, mool, arth):
    assert not re.search('[A-Za-z0-9]', arth), (shirshak, arth)
    assert not re.search('[A-Za-z0-9॒॑᳐-᳿꣠-ꣿ]', '\n'.join(mool)), (shirshak, mool)
    lines = [x + (' ॥' if i == len(mool) - 1 else ' ।') for i, x in enumerate(mool)]
    return '# %s\n%s\n= %s' % (shirshak, '\n'.join(lines), arth)


def likho():
    mantra = [s for s, _, _ in MOOL if s.startswith('मंत्र')]
    assert mantra == ['मंत्र ' + ''.join(ANK[int(d)] for d in str(n)) for n in range(1, 13)], mantra
    out = os.path.join(DST, 'paath', 'narayana.txt')
    with io.open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n\n'.join(blk(*m) for m in MOOL) + '\n')
    print('लिखा paath/narayana.txt ·', len(mantra), 'मंत्र +', len(MOOL) - len(mantra), 'जुड़े')


# ── मिलान ──────────────────────────────────────────────────────────────────────
def _tankit(path):
    """टंकित संग्रह की देवनागरी पंक्तियाँ — स्वर-चिह्न और ꣳ/ग्ं हटाकर, दंड पर काटकर।"""
    t = io.open(path, encoding='utf-8', errors='replace').read()
    t = re.sub(r'<script.*?</script>|<style.*?</style>', '', t, flags=re.S)
    t = re.sub(r'<br\s*/?>', '\n', t)
    t = html.unescape(re.sub(r'<[^>]+>', '\n', t))
    t = re.sub('[॒॑᳐-᳿꣠-ꣿ]', '', t)
    t = t.replace('ꣳ', 'ं').replace('ग्ं', 'ं').replace('ॐ', '').replace('ओं', '')
    out = []
    for x in re.split('[।॥\n]', t):
        x = re.sub(r'\s+', ' ', x).strip(' ॥।')
        if re.search('[ऀ-ॿ]', x) and len(x) > 12:
            out.append(x)
    return out


def _kunji(s):
    return re.sub('[^ऀ-ॿ]|[ःंँ्]', '', s)


def milao(sd, sn):
    gawah = {'SD': [_kunji(x) for x in _tankit(sd)], 'SN': [_kunji(x) for x in _tankit(sn)]}
    for shirshak, mool, _ in MOOL:
        for p in mool:
            k = _kunji(p)
            mile = [n for n, lines in gawah.items() if any(k == x for x in lines)]
            print('%-22s %-6s %s' % (shirshak, ' '.join(mile) or '—', p))


