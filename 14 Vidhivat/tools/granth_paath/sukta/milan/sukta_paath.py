def blk(shirshak, mool, arth):
    assert not re.search('[A-Za-z0-9]', arth), (shirshak, arth)
    assert not re.search('[A-Za-z0-9\u0951\u0952\u1cd0-\u1cff\ua8e0-\ua8ff]', '\n'.join(mool)), (shirshak, mool)
    return '# %s\n%s\n= %s' % (shirshak, '\n'.join(mool), arth)


def likho(dst, key, bl):
    with io.open(os.path.join(dst, 'paath', key + '.txt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n\n'.join(bl) + '\n')
    print(key, len(bl))


def sy_padho():
    t = html_path(io.open('sd_purusha_sy.html', encoding='utf-8', errors='replace').read())
    dv = [saaf(x) for x in t.split('\n') if re.search('[\u0900-\u097F]', x)]
    S, buf = {}, []
    for x in dv:
        m = re.search(r'\s*॥\s*([०-९]+)\s*॥\s*$', x)
        if m:
            buf.append(re.sub(r'^हरिः ॐ\s*', '', x[:m.start()]).strip())
            S[int(m.group(1).translate(ANK))] = buf
            buf = []
        elif '।' in x:
            buf.append(re.sub(r'^हरिः ॐ\s*', '', x).strip())
    return S


def main(dst):
    os.makedirs(os.path.join(dst, 'paath'), exist_ok=True)

    W = rv_milao.rv_wikisource('ws_rv10090.txt')
    likho(dst, 'purusha', [blk('मंत्र ' + da(n), panktiyan(W[n]), PURUSHA[n - 1]) for n in range(1, 17)])

    S = sy_padho()
    bl = []
    for n in range(1, 17):
        lines = [x.replace('सर्वहुतः ऋचः', 'सर्वहुत ऋचः').replace('लोकाँऽकल्पयन्', 'लोकाँ अकल्पयन्')
                 for x in S[n]]
        bl.append(blk('मंत्र ' + da(n), panktiyan(lines), YV_ALAG.get(n, PURUSHA[YV_KRAM[n - 1] - 1])))
    likho(dst, 'purusha_yv', bl)

    W = rv_milao.rv_wikisource('ws_rv10129.txt')
    likho(dst, 'nasadiya', [blk('मंत्र ' + da(n), panktiyan(W[n]), NASADIYA[n - 1]) for n in range(1, 8)])

    SD = shri_milao.mantra(shri_milao.dv('sd_shri.html'))
    lage = set()

    def sudhar(x):
        for a, b, _ in SHRI_SUDHAR:
            if a in x:
                x = x.replace(a, b)
                lage.add(a)
        return x
    bl = [blk('मंत्र ' + da(n), panktiyan([sudhar(x) for x in SD[n]]), SHRI[n - 1]) for n in range(1, 16)]
    bl.append(blk('फलश्रुति', panktiyan([sudhar(x) for x in SD[16]]), SHRI_PHAL))
    assert len(lage) == len(SHRI_SUDHAR), lage
    likho(dst, 'shri', bl)


