DA = str.maketrans('0123456789', '०१२३४५६७८९')


def da(n):
    return str(n).translate(DA)


def panktiyan(lines):
    """हर मंत्र की पंक्तियाँ एक चलन में: आख़िरी «॥» पर, बाक़ी « ।» पर।"""
    out = []
    for i, x in enumerate(lines):
        x = saaf(nfc(x).replace('ꣳ', 'ं'))
        x = re.sub(r'\s*[।॥]+\s*$', '', x)
        out.append(x + ('॥' if i == len(lines) - 1 else ' ।'))
    return out


