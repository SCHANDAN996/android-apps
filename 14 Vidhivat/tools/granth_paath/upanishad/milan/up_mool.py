FALTU = re.compile(r'^\s*(हरिः ॐ ।|हरिः ॐ ॥|॥ हरिः ॐ ॥|ॐ तत्सत् ।*|॥ ॐ ब्रह्मणे नमः ॥)\s*$')


def likhawat(s):
    s = s.replace('ꣳ', 'ं')
    s = re.sub('ँ(?=\\s?[शषसहर])', 'ं', s)
    s = s.replace('श‍ृ', 'शृ')
    s = re.sub(r'[ \t]+', ' ', s)
    s = re.sub(r'\s*॥\s*$', ' ॥', s)
    s = re.sub(r'\s*।', ' ।', s)
    return s.strip()


def panktiyan(raw):
    """S की कच्ची पंक्तियाँ (बिना अंक) → ऐप की पंक्तियाँ।"""
    lines = [x for x in raw if x.strip()]
    saaf = [x.strip() for x in lines]
    # पद्य हो या गद्य — सब जोड़कर, हर «।» पर नई पंक्ति। S पद्य के चरण अलग
    # पंक्तियों में लिखता है, पर हर जगह एक-सा नहीं (मुण्डक में चरण ग़लत जगह टूटे
    # हैं, और जहाँ चरणों के बीच संधि है वहाँ टूट ही नहीं सकते); छपी पुस्तकों की
    # तरह आधा-आधा श्लोक एक पंक्ति में — सब जगह एक ढंग।
    s = ' '.join(saaf)
    s = re.sub(r'-\s+', '', s)
    tuk = [t.strip() for t in re.split(r'(?<=[।॥])\s+', s) if t.strip()]
    return tuk


def mool(nm):
    out = []
    for sec, num, raw in s_mantra_raw('s_%s.txt' % nm):
        if not num:
            continue
        num = num.split('.')[-1]            # प्रश्न में S «१.३» लिखता है
        if '%d.%s' % (sec, num) in CHHODO.get(nm, []):
            continue
        lines = [likhawat(x) for x in panktiyan(raw)]
        out.append({'sec': sec, 'num': num, 'lines': lines})
    for pehla, doosra in JODO.get(nm, []):
        i = [n for n, m in enumerate(out) if '%d.%s' % (m['sec'], m['num']) == pehla][0]
        assert '%d.%s' % (out[i + 1]['sec'], out[i + 1]['num']) == doosra
        out[i]['lines'] += out[i + 1]['lines']
        del out[i + 1]
        for m in out[i + 1:]:
            if m['sec'] == out[i]['sec']:
                m['num'] = str(int(m['num']) - 1)
    for lab, a, b in SUDHAR.get(nm, []):
        a2 = likhawat(a) if '  ' not in a else a
        mila = 0
        for m in out:
            if '%d.%s' % (m['sec'], m['num']) != lab:
                continue
            # सुधार पूरे मंत्र पर (एक डोरी में) लगता है; फिर «।» पर पंक्तियाँ दोबारा बनती हैं
            joined = ' '.join(m['lines'])
            for aa in (a, a2, re.sub(r'\s+', ' ', a)):
                if aa in joined:
                    joined = joined.replace(aa, b)
                    mila += 1
                    break
            m['lines'] = [likhawat(t) for t in re.split(r'(?<=[।॥])\s+', joined) if t.strip()]
        if mila != 1:
            raise SystemExit('सुधार नहीं लगा: %s %s %r (%d)' % (nm, lab, a, mila))
    for lab, line in PEHLE.get(nm, {}).items():
        for m in out:
            if '%d.%s' % (m['sec'], m['num']) == lab:
                m['lines'].insert(0, line)
    for m in out:
        for l in m['lines']:
            if '॥' in l[:-1] or not (l.endswith('।') or l.endswith('॥')):
                raise SystemExit('पंक्ति का अंत ठीक नहीं: %s %d.%s %r' % (nm, m['sec'], m['num'], l))
    return out


def s_mantra_raw(name):
    """`U.s_mantra` जैसा, पर पंक्तियाँ कच्ची (आगे की जगह सहित) — चरण पहचानने के लिए।"""
    out, buf, sec = [], [], 0
    pehla = True
    for line in U.rd(name).split('\n'):
        line = U.KOSHTHAK.sub('', line)
        s = line.strip()
        if not s:
            if pehla and buf:
                out.append((0, '', buf)); buf = []
            continue
        if FALTU.match(s):
            continue
        if U.SHIRSH.search(s) and not U.ANT.search(s):
            if buf:
                out.append((0 if pehla else sec, '', buf)); buf = []
            continue
        m = U.ANT.search(s)
        if m:
            buf.append(U.ANT.sub('॥', line.rstrip()))
            num = m.group(1).translate(U.ANK)
            n = int(num.split('.')[-1])
            if pehla or n == 1:
                sec += 1
                pehla = False
            out.append((sec, num, buf)); buf = []
        else:
            buf.append(line.rstrip())
    if buf:
        out.append((sec, '', buf))
    return out


