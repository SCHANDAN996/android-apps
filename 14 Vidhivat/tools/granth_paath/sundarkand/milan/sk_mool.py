def viram(kism, i, x):
    """विराम नियम से: चौपाई — «अ। ब॥»; दोहा, सोरठा, छंद — पहली पंक्ति «।», दूसरी «॥»।
    W में पंद्रह जगह यह उलटा या अधूरा था, और (क)/(ख) के निशान पाठ में घुसे थे।"""
    x = x.replace('(क)', '').replace('(ख)', '').lstrip('-').strip()
    x = x.rstrip('।॥ ').strip()
    if kism == 'चौपाई':
        assert x.count('।') + x.count('॥') == 1, x
        x = x.replace('॥', '।')
        return x + '॥'
    assert '।' not in x and '॥' not in x, x
    return x + ('।' if i % 2 == 0 else '॥')


def main():
    W = W_padho()
    lage = set()
    ikai = []
    for n, bhag in W:
        nb = []
        for kism, lines in bhag:
            nl = []
            for x in lines:
                for i, (d, a, b) in enumerate(SUDHAR):
                    if d == n and a in x:
                        assert i not in lage, ('दो जगह मिला', d, a)
                        x = x.replace(a, b)
                        lage.add(i)
                nl.append(x)
            nl = [viram(kism, i, x) for i, x in enumerate(nl)]
            nb.append([kism, nl])
        ikai.append({'doha': n, 'bhag': nb})
    baaki = [SUDHAR[i] for i in range(len(SUDHAR)) if i not in lage]
    assert not baaki, baaki
    shlok = [ls for k, ls in D_padho() if k == 'श्लोक'][0]
    # पाँचों छपे संस्करणों में "चूडामणिम्" — बिना नुक़्ते के (संस्कृत)
    shlok = [x.replace('चूड़ामणिम्', 'चूडामणिम्').replace('विभुम् ।', 'विभुम्।') for x in shlok]
    assert any('चूडामणिम्' in x for x in shlok)
    json.dump({'shlok': shlok, 'ikai': ikai}, io.open('mool.json', 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print('✓ mool.json — %d इकाइयाँ, %d सुधार' % (len(ikai), len(SUDHAR)))


if __name__ == '__main__':
    main()
