def lagao():
    lage = pehle = 0
    for sudhar, arth_mein in ((MOOL, False), (ARTH, True)):
        for row in sudhar:
            key, sh, purana, naya = row[:4]
            p = os.path.join(PAATH, key + '.txt')
            with io.open(p, encoding='utf-8', newline='') as f:
                s = f.read()
            blocks = re.split(r'(\n\s*\n)', s)
            mila = False
            for i, blk in enumerate(blocks):
                if not blk.startswith('# ' + sh + '\n'):
                    continue
                lines = blk.split('\n')
                for j, line in enumerate(lines[1:], 1):
                    if line.startswith('= ') != arth_mein:
                        continue
                    if purana in line:
                        lines[j] = line.replace(purana, naya)
                        mila = True
                        lage += 1
                    elif naya in line:
                        mila = True
                        pehle += 1
                blocks[i] = '\n'.join(lines)
            if not mila:
                sys.exit('✗ %s %s: न पुराना मिला न नया — %s' % (key, sh, purana))
            with io.open(p, 'w', encoding='utf-8', newline='') as f:
                f.write(''.join(blocks))
    print('✓ %d सुधार लगे, %d पहले से लगे थे' % (lage, pehle))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')
    lagao()
