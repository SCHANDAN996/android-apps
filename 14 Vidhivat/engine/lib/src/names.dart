///
/// एक चांद्र मास में 60 करण होते हैं। पहला हमेशा किंस्तुघ्न, आख़िरी तीन
/// शकुनि–चतुष्पाद–नाग, और बीच के 56 में सात चर करण आठ बार दोहराते हैं।
int karanaNameIndex(int karanaCount) {
  if (karanaCount == 0) return 10; // किंस्तुघ्न
  if (karanaCount == 57) return 7; // शकुनि
  if (karanaCount == 58) return 8; // चतुष्पाद
  if (karanaCount == 59) return 9; // नाग
  return (karanaCount - 1) % 7;
}

