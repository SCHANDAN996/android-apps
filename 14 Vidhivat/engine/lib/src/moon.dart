/// चंद्र के मूल कोण। तीनों गणनाओं (देशांतर, अक्षांश, दूरी) को यही चाहिए,
/// इसलिए एक ही जगह निकालकर तीनों को दे दिए जाते हैं।
typedef _MoonArgs = ({
  double lPrime,
  double d,
  double m,
  double mPrime,
  double f,
  double a1,
  double a2,
  double a3,
  double e,
});

_MoonArgs _args(double jde) {
  final t = julianCenturies(jde);
  final t2 = t * t;
  final t3 = t2 * t;
  final t4 = t3 * t;

  return (
    // चंद्र का माध्य देशांतर
    lPrime: 218.3164477 +
        481267.88123421 * t -
        0.0015786 * t2 +
        t3 / 538841.0 -
        t4 / 65194000.0,

    // माध्य दूरी (सूर्य से)
    d: 297.8501921 +
        445267.1114034 * t -
        0.0018819 * t2 +
        t3 / 545868.0 -
        t4 / 113065000.0,

    // सूर्य की माध्य विसंगति
    m: 357.5291092 + 35999.0502909 * t - 0.0001536 * t2 + t3 / 24490000.0,

    // चंद्र की माध्य विसंगति
    mPrime: 134.9633964 +
        477198.8675055 * t +
        0.0087414 * t2 +
        t3 / 69699.0 -
        t4 / 14712000.0,

    // अक्षांश-कोण
    f: 93.2720950 +
        483202.0175233 * t -
        0.0036539 * t2 -
        t3 / 3526000.0 +
        t4 / 863310000.0,

    // शुक्र, बृहस्पति और चपटेपन का असर
    a1: 119.75 + 131.849 * t,
    a2: 53.09 + 479264.290 * t,
    a3: 313.45 + 481266.484 * t,

    // पृथ्वी की कक्षा की विकेंद्रता बदलती रहती है — M वाले पदों पर यही सुधार
    e: 1 - 0.002516 * t - 0.0000074 * t2,
  );
}

/// M का गुणांक ±1 हो तो E से, ±2 हो तो E² से गुणा। भूलना आसान है और
/// चुपचाप ग़लती करता है।
double _eccentricityFactor(int mCoefficient, double e) {
  final absM = mCoefficient.abs();
  if (absM == 1) return e;
  if (absM == 2) return e * e;
  return 1.0;
}

/// चंद्रमा का सायन (tropical) **आभासी** देशांतर, डिग्री। JDE (TT) चाहिए।
double moonLongitude(double jde) {
  final a = _args(jde);

  var sumL = 0.0;
  for (final term in _longitudeTerms) {
    final coefficient = term[4];
    if (coefficient == 0) continue;
    final argument =
        term[0] * a.d + term[1] * a.m + term[2] * a.mPrime + term[3] * a.f;
    sumL += coefficient * _eccentricityFactor(term[1], a.e) * sinD(argument);
  }

  // तालिका से बाहर के तीन जोड़
  sumL += 3958.0 * sinD(a.a1);
  sumL += 1962.0 * sinD(a.lPrime - a.f);
  sumL += 318.0 * sinD(a.a2);

  // यहाँ तक जो निकला वो *ज्यामितीय* देशांतर है, माध्य विषुव के सापेक्ष।
  // आभासी (apparent) बनाने के लिए नतांश जोड़ना ज़रूरी है — सूर्य में
  // यह पहले से जुड़ा है (Meeus का −0.00478·sin Ω वाला पद), इसलिए चंद्र
  // में भी जुड़ना चाहिए। न जोड़ो तो तिथि आधा मिनट खिसक जाती है।
  return norm360(a.lPrime + sumL / 1000000.0 + nutationInLongitude(jde));
}

/// चंद्रमा का अक्षांश (β), डिग्री। −5.2° से +5.2° के बीच रहता है।
///
/// ⚠️ अक्षांश पर **नतांश नहीं लगता** — वो सिर्फ़ देशांतर को खिसकाता है।
double moonLatitude(double jde) {
  final a = _args(jde);

  var sumB = 0.0;
  for (final term in _latitudeTerms) {
    final coefficient = term[4];
    if (coefficient == 0) continue;
    final argument =
        term[0] * a.d + term[1] * a.m + term[2] * a.mPrime + term[3] * a.f;
    sumB += coefficient * _eccentricityFactor(term[1], a.e) * sinD(argument);
  }

  // तालिका से बाहर के छह जोड़
  sumB += -2235.0 * sinD(a.lPrime);
  sumB += 382.0 * sinD(a.a3);
  sumB += 175.0 * sinD(a.a1 - a.f);
  sumB += 175.0 * sinD(a.a1 + a.f);
  sumB += 127.0 * sinD(a.lPrime - a.mPrime);
  sumB += -115.0 * sinD(a.lPrime + a.mPrime);

  return sumB / 1000000.0;
}

/// पृथ्वी के केंद्र से चंद्रमा की दूरी, किलोमीटर।
/// लगभग 356400 (सबसे पास) से 406700 (सबसे दूर) तक।
double moonDistance(double jde) {
  final a = _args(jde);

  var sumR = 0.0;
  for (var i = 0; i < _longitudeTerms.length; i++) {
    final coefficient = _distanceCoefficients[i];
    if (coefficient == 0) continue;
    final term = _longitudeTerms[i];
    final argument =
        term[0] * a.d + term[1] * a.m + term[2] * a.mPrime + term[3] * a.f;
    sumR += coefficient * _eccentricityFactor(term[1], a.e) * cosD(argument);
  }

  return 385000.56 + sumR / 1000.0;
}

/// चंद्रमा का क्षैतिज लंबन (horizontal parallax), डिग्री। लगभग 0.95°।
///
/// **यही सूर्य और चंद्र के उदय-अस्त में सबसे बड़ा फ़र्क़ है।** सूरज इतनी
/// दूर है कि उसका लंबन नगण्य है, पर चंद्रमा पास है — इसलिए वो क्षितिज
/// पर हमारी सोच से लगभग एक डिग्री ऊपर दिखता है।
double moonParallax(double jde) => asinD(6378.14 / moonDistance(jde));

/// चंद्र का माध्य देशांतर — जाँच के लिए।
double moonMeanLongitude(double jde) => norm360(_args(jde).lPrime);

/// चंद्र का *ज्यामितीय* देशांतर — नतांश के बिना, माध्य विषुव के सापेक्ष।
/// जाँच और तुलना के लिए।
double moonGeometricLongitude(double jde) =>
    norm360(moonLongitude(jde) - nutationInLongitude(jde));
