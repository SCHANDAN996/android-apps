import 'angles.dart';
import 'julian.dart';

/// नतांश (nutation) — पृथ्वी की धुरी का हल्का डोलना।
///
/// इससे सारे देशांतर थोड़ा आगे-पीछे खिसकते हैं, ज़्यादा से ज़्यादा
/// 17 विकला (0.0047°)। छोटा लगता है, पर चंद्रमा 13° रोज़ चलता है —
/// तो 0.0047° का मतलब है समय में लगभग आधा मिनट। नक्षत्र की समाप्ति
/// का समय बताते वक़्त वही आधा मिनट दिखता है।
///
/// **सूर्य और चंद्र दोनों पर यही सुधार लगना चाहिए।** एक पर लगाओ और
/// दूसरे पर भूल जाओ, तो तिथि (चंद्र − सूर्य) में ग़लती आ जाएगी।
///
/// संदर्भ: Meeus, अध्याय 22 (सरल रूप, ~0.5 विकला तक सही)।
double nutationInLongitude(double jde) {
  final t = julianCenturies(jde);

  // चंद्र-कक्षा का आरोही पात
  final omega = 125.04452 - 1934.136261 * t;

  // सूर्य और चंद्र के माध्य देशांतर
  final sunMean = 280.4665 + 36000.7698 * t;
  final moonMean = 218.3165 + 481267.8813 * t;

  final arcseconds = -17.20 * sinD(omega) -
      1.32 * sinD(2 * sunMean) -
      0.23 * sinD(2 * moonMean) +
      0.21 * sinD(2 * omega);

  return arcseconds / 3600.0;
}
