import 'julian.dart';

/// अयनांश — सायन (tropical) और निरयन (sidereal) देशांतर के बीच का फ़र्क़।
///
/// भारत में सरकारी तौर पर **लाहिड़ी (चित्रपक्ष)** अयनांश चलता है, और
/// ठाकुर प्रसाद, लाला रामस्वरूप जैसे छपे पंचांग भी यही मानते हैं।
/// इसलिए ऐप में यही रहेगा।
///
///   निरयन देशांतर = सायन देशांतर − अयनांश
///
/// ⚠️ यही वो एक जगह है जहाँ छोटी सी ग़लती पूरे पंचांग को हिला सकती है।
/// नीचे का सूत्र लगभग 0.005° (18 विकला) तक सही है — नक्षत्र 13°20' का
/// होता है, तो इससे नक्षत्र कभी ग़लत नहीं होगा। फिर भी छपे पंचांग से
/// मिलाना ज़रूरी है, और मिलान न हो तो [ayanamsaCalibration] घुमाना।

/// अगर छपे पंचांग से थोड़ा फ़र्क़ मिले तो यहीं सुधार डालो, डिग्री में।
/// (1 विकला = 0.000278°)। बाक़ी कोड को हाथ मत लगाना।
double ayanamsaCalibration = 0.0;

/// लाहिड़ी अयनांश, डिग्री में। JDE (TT) चाहिए।
///
/// **मान कैसे तय हुआ (20 अगस्त 2026):**
/// Drik Panchang से दो तारीख़ें मिलाईं, 9.4 साल के फ़ासले पर —
///
/// | तारीख़ | Drik | हमारा (सुधार से पहले) | फ़र्क़ |
/// |---|---|---|---|
/// | 20-08-2026 | 24.235869° | 24.225000° | 0.010869° |
/// | 14-01-2036 | 24.367229° | 24.356361° | 0.010868° |
///
/// फ़र्क़ दोनों जगह एक ही निकला — यानी **चाल सही थी, सिर्फ़ शुरुआती मान
/// 39 विकला नीचे था।** इसलिए नीचे वाला स्थिरांक उतना ही बढ़ा दिया।
/// अब दोनों तारीख़ों पर मिलान 0.000001° के भीतर है।
double lahiriAyanamsa(double jde) {
  final t = julianCenturies(jde);

  // J2000.0 पर लाहिड़ी अयनांश, और सामान्य अयन-चलन लगभग
  // 50.29 विकला प्रति वर्ष (यानी 1.39697° प्रति शताब्दी)।
  final value = 23.8637885 + 1.3969713 * t + 0.0003086 * t * t;

  return value + ayanamsaCalibration;
}

/// सायन → निरयन।
double toSidereal(double tropicalLongitude, double jde) {
  final v = tropicalLongitude - lahiriAyanamsa(jde);
  final n = v % 360.0;
  return n < 0 ? n + 360.0 : n;
}
