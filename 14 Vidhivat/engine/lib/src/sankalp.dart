/// संकल्प वाक्य — **ऐप का सबसे बड़ा हथियार।**
///
/// हर पूजा संकल्प से शुरू होती है, और संकल्प में आज का संवत्, अयन, ऋतु,
/// मास, पक्ष, तिथि, वार और नक्षत्र सब बोलना पड़ता है। **यही वो जगह है
/// जहाँ हर आदमी अटकता है और पंडित जी को बुलाना पड़ता है।**
///
/// हमारे पास पंचांग इंजन है, इसलिए हम यह वाक्य **ख़ुद बना सकते हैं** —
/// यूज़र से सिर्फ़ नाम, गोत्र और जगह पूछकर। बाज़ार में किसी ऐप के पास
/// यह नहीं है।
///
/// ## ⚠️ मुहर नहीं, स्रोत (→ D-041)
///
/// पहले यहाँ लिखा था *"पंडित जी से पास होनी बाक़ी है।"* वह इंतज़ार अब
/// छोड़ दिया गया — डेवलपर ने **10–15 पंडितों को दिखाया और वे आपस में ही
/// नहीं मिले।** एक पंडित की मुहर = **एक पद्धति का जवाब**, सार्वभौम सच
/// नहीं। उसे लगा देते तो ऐप बाक़ी हर पद्धति को चुपचाप "ग़लत" कह देता।
///
/// इसलिए अब नियम यह है:
///
/// * जो **व्याकरण** से सिद्ध है, वह ठीक किया गया (तिथि की सप्तमी → A2,
///   यजमान का लिंग → A3)
/// * जिसका **छपा स्रोत** मिला, वह उसी रूप में है, और स्रोत
///   `docs/18_SROT_PANJI.md` में दर्ज है (जगह का रूप → A5)
/// * जहाँ **कई प्रकाशित रूप** मिले, वहाँ ऐप **चुनता नहीं** — दोनों
///   दिखाता है (भूगोल का क्रम, पूर्णिमा का रूप)
/// * जहाँ **कुछ नहीं मिला**, वहाँ ख़ाली और वजह लिखी हुई
///
/// [Sankalp.needsPanditReview] अब भी सच है, पर उसका मतलब बदल गया —
/// *"पास नहीं हुआ"* नहीं, बल्कि **"इसका स्रोत यह है, और दूसरा चलन भी
/// है।"** चेतावनी हटी नहीं, ईमानदार हुई।
///
/// D-009 नहीं टूटा: *मंत्र ग़लत होना तिथि ग़लत होने से भी बुरा है* —
/// इसीलिए अंदाज़े से कुछ नहीं लिखा गया।
///
/// क्षेत्रीय फ़र्क़ रहेंगे ही, इसलिए एक **सरल रूप** भी दिया गया है जो
/// हर जगह चल जाता है।

/// यजमान पुरुष है या स्त्री — संकल्प का वाक्य इसी से बदलता है।
///
/// ## यह क्यों ज़रूरी है (→ A3)
///
/// पहले ऐप हर यजमान को **पुल्लिंग** मान लेता था — हर स्त्री के लिए भी
/// *"…गोत्रोत्पन्नः"* बनता था, जो साफ़ ग़लत है।
///
/// ## यह "मंत्र बदलना" नहीं है
///
/// संकल्प कोई बँधा हुआ मंत्र नहीं है — यह **बोलने वाले के बारे में एक
/// वाक्य** है, जो हर बार नया भरा जाता है (नाम, गोत्र, जगह, तिथि — सब
/// बदलते हैं)। इसलिए उसे बोलने वाले के लिंग से मिलाना वही काम है जिसके
/// लिए वह वाक्य बना है। यह उस नियम के ख़िलाफ़ नहीं जाता जो क्षमा-श्लोक
/// जैसे **बँधे हुए छन्दोबद्ध पाठ** में शब्द बदलने से रोकता है (→ A4)।
///
/// ⬜ **दम्पति (द्विवचन) का रूप अभी नहीं है** — वह अलग है और उसका
/// प्रामाणिक पाठ नहीं मिला, इसलिए जान-बूझकर नहीं जोड़ा।
enum Yajaman {
  /// पुरुष — `…गोत्रोत्पन्नः …नामाहम्`
  purush,

  /// स्त्री — `…गोत्रोत्पन्ना …नाम्नी अहम्`
  stri,
}

/// जगह किस तरह की है — नगर, गाँव या तीर्थ।
///
/// ## यह क्यों जुड़ा (→ A5)
///
/// पहले ऐप हर जगह के साथ *"क्षेत्रे"* जोड़ देता था — *"गुड़गाँव क्षेत्रे"*,
/// *"नोएडा क्षेत्रे"*। पर **"क्षेत्र" पुण्यक्षेत्रों के लिए बोला जाता
/// है** (काशी, प्रयाग, गया, मथुरा, अयोध्या, कुरुक्षेत्र, हरिद्वार)।
/// साधारण शहर के लिए **नगरे**, गाँव के लिए **ग्रामे**।
///
/// ## और शहर का संस्कृत रूप गढ़ना नहीं पड़ता
///
/// छपी पद्धति में इसका जवाब पहले से है — **`अमुकनाम्नि नगरे (ग्रामे वा)`**
/// यानी *"अमुक नाम वाले नगर में"*। जगह का नाम संस्कृत में ढालने की
/// ज़रूरत ही नहीं पड़ती; वाक्य ख़ुद उसे *"जिसका नाम यह है"* कहकर जोड़ता
/// है। (स्रोत → `docs/18_SROT_PANJI.md` §1.3)
enum SthanPrakar {
  /// शहर — `<नाम>नाम्नि नगरे`
  nagar,

  /// गाँव — `<नाम>नाम्नि ग्रामे`
  gram,

  /// तीर्थ / पुण्यक्षेत्र — `<नाम>नाम्नि पुण्यक्षेत्रे`
  kshetra,
}

/// यजमान की जानकारी — एक बार पूछो, फिर हमेशा याद रखो।
class SankalpDetails {
  /// यजमान का नाम, जैसे "चन्दन सिंह"
  final String name;

  /// गोत्र, जैसे "कश्यप"। न पता हो तो "कश्यप" ही आम चलन है।
  final String gotra;

  /// जगह का नाम, जैसे "दिल्ली"
  final String place;

  /// किस काम का संकल्प, जैसे "श्री सत्यनारायण पूजनं"
  final String purpose;

  /// पुरुष या स्त्री — वाक्य इसी से बदलता है।
  final Yajaman yajaman;

  /// जगह नगर है, गाँव है या तीर्थ।
  final SthanPrakar sthanPrakar;

  const SankalpDetails({
    required this.name,
    required this.gotra,
    required this.place,
    required this.purpose,
    this.yajaman = Yajaman.purush,
    this.sthanPrakar = SthanPrakar.nagar,
  });
}

/// बना हुआ संकल्प — पूरा वाक्य, और हर हिस्सा अलग से भी।
