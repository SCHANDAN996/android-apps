/// यूज़र का भरा हुआ नाम अगले पद से जोड़ो — पर **समझदारी से**।
///
/// पद्धति में साँचा `अमुकनामा` / `अमुकनाम्नि` है, यानी नाम अगले पद से
/// जुड़ा हुआ। एक शब्द के नाम पर यह ठीक बैठता है — *दिल्लीनाम्नि*।
///
/// पर यूज़र का नाम अपने आप में कई शब्दों का हो सकता है ("चन्दन सिंह",
/// "राहुल कुमार शर्मा", "नई दिल्ली")। वहाँ सीधे चिपकाने से
/// *"चन्दन सिंहनामाहम्"* जैसा अटपटा रूप बनता है, जिसमें जोड़ सिर्फ़
/// आख़िरी शब्द से लगा दिखता है — जबकि नाम पूरा एक इकाई है।
///
/// इसलिए: **एक शब्द हो तो जोड़ो, कई शब्द हों तो जगह छोड़ो।**
/// बोलने में दोनों एक जैसे हैं; यह सिर्फ़ पढ़ने वाले के लिए है।
///
/// ⚠️ ऐप का नाम-वाला खाना यूज़र भरता है — इसलिए यहाँ कुछ भी आ सकता है।
/// इसीलिए नाम को संस्कृत में **ढाला नहीं जाता**, सिर्फ़ जोड़ा जाता है
/// (→ `docs/18_SROT_PANJI.md` §1.3, §1.4)।
String _naamSe(String naam, String pratyay) {
  final saaf = naam.trim();
  return saaf.contains(' ') ? '$saaf $pratyay' : '$saaf$pratyay';
}

