/// एक शहर — नाम, राज्य, और उसका अक्षांश-देशांतर।
class City {
  final String name;
  final String state;
  final double latitude;
  final double longitude;
  final bool isDeviceDetected;

  /// ── यूज़र ने जगह का नाम ख़ुद लिखा है ─────────────────
  ///
  /// सूची चाहे जितनी बड़ी हो, **गाँव उसमें कभी नहीं आएगा** — भारत
  /// में छह लाख से ज़्यादा गाँव हैं। और संकल्प में जगह का नाम बोला
  /// जाता है — वहाँ "रायपुर" कहना जब आप अंबिकापुर में हैं, ग़लत है।
  ///
  /// ⚠ इससे **गणित नहीं बदलता।** अक्षांश-देशांतर वही रहते हैं जो
  /// फ़ोन या चुने हुए शहर से आए थे — सिर्फ़ **नाम** बदलता है।
  final bool naamKhudLikha;

  const City(
    this.name,
    this.state,
    this.latitude,
    this.longitude, {
    this.isDeviceDetected = false,
    this.naamKhudLikha = false,
  });

  /// वही जगह, पर यूज़र का लिखा हुआ नाम। अक्षांश-देशांतर वही।
  City withNaam(String naya) => City(
        naya.trim(),
        state,
        latitude,
        longitude,
        isDeviceDetected: isDeviceDetected,
        naamKhudLikha: true,
      );

  factory City.fromDeviceLocation(double latitude, double longitude) {
    final nearby = nearestIndianCity(latitude, longitude);
    return City(
      nearby.name,
      nearby.state,
      latitude,
      longitude,
      isDeviceDetected: true,
    );
  }

  factory City.fromJson(Map<String, dynamic> json) {
    final name = json['name'];
    final state = json['state'];
    final latitude = json['latitude'];
    final longitude = json['longitude'];
    if (name is! String ||
        state is! String ||
        latitude is! num ||
        longitude is! num ||
        latitude < -90 ||
        latitude > 90 ||
        longitude < -180 ||
        longitude > 180) {
      throw const FormatException('Invalid local city');
    }
    return City(
      name,
      state,
      latitude.toDouble(),
      longitude.toDouble(),
      isDeviceDetected: json['isDeviceDetected'] == true,
      naamKhudLikha: json['naamKhudLikha'] == true,
    );
  }

  Map<String, Object> toJson() => {
        'name': name,
        'state': state,
        'latitude': latitude,
        'longitude': longitude,
        'isDeviceDetected': isDeviceDetected,
        'naamKhudLikha': naamKhudLikha,
      };

  String get cacheKey => '$name|$state|$latitude|$longitude';
  /// यह नाम कहाँ से आया — और यह सच-सच कहना ज़रूरी है।
  ///
  /// पहले यह सिर्फ़ दो बातें कहता था — "फ़ोन से" या "हाथ से
  /// चुना गया"। पर जब यूज़र ने कुछ चुना ही न हो, तब "हाथ से चुना
  /// गया" **झूठ** है — वो ऐप का अपना डिफ़ॉल्ट होता है (→ D-058)।
  String get locationSourceLabel {
    if (naamKhudLikha) return '$state · आपका लिखा हुआ नाम';
    if (isDeviceDetected) return '$state · फ़ोन से पहचाना गया स्थान';
    return '$state · हाथ से चुना गया';
  }

  /// इंजन के लिए जगह। समय-क्षेत्र भारत का ही (IST)।
  Place get place => Place(
        name: name,
        latitude: latitude,
        longitude: longitude,
      );

  @override
  String toString() => '$name, $state';
}

/// Offline nearest-city label. Panchang calculations still use the exact
/// device coordinates retained in [City], not the centre of this known city.
City nearestIndianCity(double latitude, double longitude) {
  return indianCities.reduce((closest, candidate) {
    final closestDistance = _coordinateDistanceSquared(
      latitude,
      longitude,
      closest.latitude,
      closest.longitude,
    );
    final candidateDistance = _coordinateDistanceSquared(
      latitude,
      longitude,
      candidate.latitude,
      candidate.longitude,
    );
    return candidateDistance < closestDistance ? candidate : closest;
  });
}

double _coordinateDistanceSquared(
  double latitudeA,
  double longitudeA,
  double latitudeB,
  double longitudeB,
) {
  final latitudeDelta = latitudeA - latitudeB;
  final longitudeDelta = longitudeA - longitudeB;
  return latitudeDelta * latitudeDelta + longitudeDelta * longitudeDelta;
}

