  static const Set<String> _devanagari = {'hi', 'bho', 'mr'};

  String translate(String key) {
    final code = locale.languageCode;

    // ⚠️ पहले यहाँ हर भाषा के लिए **हिंदी** पर fallback होता था। नतीजा: तमिल,
    // तेलुगु, कन्नड़, बांग्ला, गुजराती और पंजाबी चुनने वाले को 86% ऐप
    // देवनागरी में दिखता था — जो वह पढ़ ही नहीं सकता।
    //
    // अब देवनागरी न पढ़ने वालों के लिए पहले **अंग्रेज़ी** पर जाते हैं। भारत में
    // देवनागरी की तुलना में अंग्रेज़ी कहीं ज़्यादा लोग पढ़ लेते हैं, और अंग्रेज़ी
    // वाला हिस्सा पूरा भरा हुआ है (712/712)।
    final fallbackOrder = _devanagari.contains(code)
        ? const ['hi', 'en']
        : const ['en', 'hi'];

    final own = _localizedValues[code]?[key] ?? kExtraTranslations[code]?[key];
    if (own != null) return own;

    for (final f in fallbackOrder) {
      final v = _localizedValues[f]?[key] ?? kExtraTranslations[f]?[key];
      if (v != null) return v;
    }
    return key;
  }

  static String get(BuildContext context, String key) {
    return of(context).translate(key);
  }
