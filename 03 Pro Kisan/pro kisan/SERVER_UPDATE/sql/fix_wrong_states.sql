--
--  क्या हुआ था:
--  पहली sync में स्क्रिप्ट हर पंक्ति पर **वही राज्य** चिपका देती थी जो
--  उसने API से माँगा था। पर data.gov.in का filters[state] भरोसेमंद नहीं —
--  "Andaman and Nicobar" माँगने पर 110 पंक्तियाँ आईं जिनमें 93 जम्मू-कश्मीर
--  की थीं। नतीजा: कश्मीर के सेब "अंडमान और निकोबार" के नाम से सहेजे गए।
--
--  नई sync हर पंक्ति का अपना राज्य पढ़ती है, इसलिए आगे यह नहीं होगा।
--  पर पुरानी ग़लत पंक्तियाँ टेबल में पड़ी रहेंगी — UNIQUE key में राज्य भी
--  शामिल है, तो सही पंक्ति *नई* बनेगी और ग़लत वाली अपने आप नहीं हटेगी।
--
--  चलाने का तरीक़ा:
--    mysql -u prokisan_user -p pro_kisan_db < fix_wrong_states.sql
--    फिर: php cron/mandi_sync.php
-- ═══════════════════════════════════════════════════════════════

-- पहले देख लें कि कितना गड़बड़ है
SELECT state AS 'राज्य', COUNT(*) AS 'भाव'
  FROM mandi_rates
 GROUP BY state
 ORDER BY COUNT(*) DESC;

