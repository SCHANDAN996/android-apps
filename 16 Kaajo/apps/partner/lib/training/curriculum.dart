/// एक पाठ (3–5 मिनट)। स्क्रीन पर इसी क्रम में दिखता है:
/// आज क्या सीखेंगे → मुख्य बातें → ऐसे करें → ऐसा कभी न करें → क्यों ज़रूरी → याद रखें।
class Lesson {
  const Lesson({
    required this.id,
    required this.title,
    required this.goal,
    required this.points,
    this.doList = const [],
    this.dontList = const [],
    required this.why,
    required this.remember,
    this.minutes = 4,
  });

  /// जैसे `d2l1` (दिन 2, पाठ 1)।
  final String id;
  final String title;

  /// 🎯 आज क्या सीखेंगे (एक लाइन)।
  final String goal;

  /// 📋 मुख्य बातें, क्रम से।
  final List<String> points;

  /// ✅ ऐसे करें।
  final List<String> doList;

  /// ❌ ऐसा कभी न करें।
  final List<String> dontList;

  /// 💡 क्यों ज़रूरी।
  final String why;

  /// 🧠 याद रखें (एक लाइन का निचोड़)।
  final String remember;

  /// पढ़ने में लगभग कितने मिनट।
  final int minutes;
}

/// क्विज़ का एक सवाल: चार विकल्प, एक सही।
class QuizQuestion {
  const QuizQuestion({
    required this.question,
    required this.options,
    required this.correctIndex,
    required this.explanation,
  });

  final String question;
  final List<String> options;
  final int correctIndex;

  /// ग़लत जवाब पर दिखने वाली वजह (सही जवाब के बाद भी दिखती है)।
  final String explanation;

  String get correctOption => options[correctIndex];
}

/// ट्रेनिंग का एक दिन (1–5): पाठ और शाम की क्विज़।
class TrainingDay {
  const TrainingDay({
    required this.id,
    required this.number,
    required this.title,
    required this.goal,
    required this.lessons,
    required this.quiz,
  });

  /// जैसे `day1`।
  final String id;
  final int number;
  final String title;
  final String goal;
  final List<Lesson> lessons;
  final List<QuizQuestion> quiz;
}

