/// id से दिन (1–5)। न मिले तो null।
TrainingDay? dayById(String dayId) {
  for (final d in trainingDays) {
    if (d.id == dayId) return d;
  }
  return null;
}

/// दिन के अंदर id से पाठ। न मिले तो null।
Lesson? lessonById(TrainingDay day, String lessonId) {
  for (final l in day.lessons) {
    if (l.id == lessonId) return l;
  }
  return null;
}

/// पाठ का नंबर, जैसे "2.3"।
String lessonNumber(TrainingDay day, Lesson lesson) {
  final i = day.lessons.indexWhere((l) => l.id == lesson.id);
  return '${day.number}.${i < 0 ? 1 : i + 1}';
}

